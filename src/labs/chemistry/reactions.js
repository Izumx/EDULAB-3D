// Atom counts of one side with the given coefficients
export function sideAtoms(side, coefs) {
    const symbols = [];
    side.forEach(([id], i) => {
        const mol = BY_ID.get(id);
        for (let k = 0; k < coefs[i]; k++) {
            for (const [el, n] of Object.entries(mol.comp)) for (let j = 0; j < n; j++) symbols.push(el);
        }
    });
    return countAtoms(symbols);
}

// Rows of the balance table: element, count on the left, count on the right
export function balanceRows(reaction, leftCoefs, rightCoefs) {
    const L = sideAtoms(reaction.left, leftCoefs);
    const R = sideAtoms(reaction.right, rightCoefs);
    const els = [...new Set([...Object.keys(L), ...Object.keys(R)])];
    return els.map(el => ({ el, left: L[el] || 0, right: R[el] || 0 }));
}

export const isBalanced = rows => rows.every(r => r.left === r.right);

